/*
 * Названия категорий в отчёте технические: «CI/CD», «Работа с issues».
 * Здесь к каждому коду привязано объяснение обычными словами — чтобы отчёт
 * читался и тем, кто не пишет код. Коды перечислены в docs/api-contract.md.
 * Незнакомый код объяснения не получает: выдумывать за backend нельзя.
 */

const meanings: Record<string, string> = {
  security: "Нет ли в коде и подключённых библиотеках известных уязвимостей",
  cicd: "Собирается ли проект сам и проходят ли проверки перед выкладкой",
  documentation: "Понятно ли из описания, как запустить проект и чем помочь",
  activity: "Живой ли проект: часто ли пишут код и выходят ли новые версии",
  issues: "Отвечают ли на присланные задачи и не копятся ли забытые",
  code_health: "Сколько в коде накопилось долгов и устаревших библиотек",
};

/** Объяснение категории обычными словами; null — код незнакомый. */
export function describeCategory(code: string): string | null {
  return meanings[code] ?? null;
}
