import { getScoreBand } from "./scoreBands";

/*
 * Первое, что видно в отчёте, — не число, а фраза обычными словами.
 * Число объясняет, насколько всё хорошо, только тому, кто знает шкалу;
 * фраза понятна сразу и тому, кто открыл отчёт впервые.
 */

export interface Verdict {
  /** Крупная фраза над оценкой. */
  title: string;
  /** Одна строка: что означает оценка и насколько ей можно верить. */
  note: string;
}

const titles = {
  high: "Проект в хорошем состоянии",
  mid: "Проект рабочий, но есть что поправить",
  low: "Проект требует внимания",
} as const;

/**
 * Вердикт по оценке. Отсутствие оценки — это не «плохо»,
 * а отсутствие данных, и формулировка это проговаривает.
 */
export function scoreVerdict(score: number | null, isPreliminary: boolean): Verdict {
  if (score === null) {
    return {
      title: "Оценку пока не из чего посчитать",
      note: "Ни по одной части проекта не удалось собрать данные. Это не значит, что с ним что-то не так.",
    };
  }

  const title = titles[getScoreBand(score)];
  const note = isPreliminary
    ? "Оценка предварительная: посчитали не всё, и после сбора остальных данных она может измениться."
    : "Оценка полная: учтены все части проекта, которые к нему относятся.";

  return { title, note };
}
